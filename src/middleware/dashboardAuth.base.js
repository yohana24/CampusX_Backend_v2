'use strict';

const crypto = require('node:crypto');

const COOKIE_NAME = 'campusx_session';
const rawSessionHours = Number(process.env.DASHBOARD_SESSION_HOURS || 8);
const SESSION_HOURS = Number.isFinite(rawSessionHours) ? Math.min(24, Math.max(1, rawSessionHours)) : 8;
const SESSION_MAX_AGE_SECONDS = SESSION_HOURS * 60 * 60;
const USERNAME = String(process.env.DASHBOARD_USERNAME || '').trim();
const PASSWORD_HASH = String(process.env.DASHBOARD_PASSWORD_HASH || '').trim();
const SESSION_SECRET = String(process.env.DASHBOARD_SESSION_SECRET || '').trim();
const COOKIE_SECURE = String(process.env.DASHBOARD_COOKIE_SECURE || 'false').toLowerCase() === 'true';
const AUTH_CONFIGURED = Boolean(USERNAME && PASSWORD_HASH && SESSION_SECRET.length >= 32);
const loginAttempts = new Map();

function safeEqual(a, b) {
  const left = Buffer.from(String(a));
  const right = Buffer.from(String(b));
  return left.length === right.length && crypto.timingSafeEqual(left, right);
}

function parseCookies(header = '') {
  const result = Object.create(null);
  for (const part of header.split(';')) {
    const separator = part.indexOf('=');
    if (separator <= 0) continue;
    const name = part.slice(0, separator).trim();
    const value = part.slice(separator + 1).trim();
    try { result[name] = decodeURIComponent(value); } catch { result[name] = value; }
  }
  return result;
}

function sign(value) {
  return crypto.createHmac('sha256', SESSION_SECRET).update(value).digest('base64url');
}

function createSession(username) {
  const now = Date.now();
  const payload = Buffer.from(JSON.stringify({
    username,
    issuedAt: now,
    expiresAt: now + SESSION_MAX_AGE_SECONDS * 1000,
    nonce: crypto.randomBytes(12).toString('hex'),
  })).toString('base64url');
  return `${payload}.${sign(payload)}`;
}

function readSession(req) {
  if (!AUTH_CONFIGURED) return null;
  const token = parseCookies(req.headers.cookie)[COOKIE_NAME];
  if (!token || typeof token !== 'string') return null;
  const [payload, signature, extra] = token.split('.');
  if (!payload || !signature || extra !== undefined || !safeEqual(signature, sign(payload))) return null;
  try {
    const data = JSON.parse(Buffer.from(payload, 'base64url').toString('utf8'));
    if (!data.username || data.username.toLowerCase() !== USERNAME.toLowerCase()) return null;
    if (!Number.isFinite(data.expiresAt) || data.expiresAt <= Date.now()) return null;
    return { username: data.username, expiresAt: data.expiresAt };
  } catch {
    return null;
  }
}

function sessionMiddleware(req, res, next) {
  req.dashboardUser = readSession(req);
  next();
}

function clearLoginAttempt(ip) {
  loginAttempts.delete(ip);
}

function checkLoginRate(ip) {
  const entry = loginAttempts.get(ip);
  if (!entry) return { blocked: false };
  if (entry.blockedUntil && entry.blockedUntil > Date.now()) {
    return { blocked: true, retryAfter: Math.ceil((entry.blockedUntil - Date.now()) / 1000) };
  }
  if (entry.blockedUntil && entry.blockedUntil <= Date.now()) loginAttempts.delete(ip);
  return { blocked: false };
}

function recordFailedLogin(ip) {
  const current = loginAttempts.get(ip) || { failures: 0, blockedUntil: 0 };
  current.failures += 1;
  if (current.failures >= 5) {
    current.blockedUntil = Date.now() + 15 * 60 * 1000;
    current.failures = 0;
  }
  loginAttempts.set(ip, current);
}

function verifyPassword(password) {
  // Expected env format: saltHex:derivedKeyHex (generated by scripts/create-dashboard-credentials.js).
  const separator = PASSWORD_HASH.indexOf(':');
  if (separator <= 0) return false;
  const saltHex = PASSWORD_HASH.slice(0, separator);
  const expectedHex = PASSWORD_HASH.slice(separator + 1);
  if (!/^[a-f0-9]{32,128}$/i.test(saltHex) || !/^[a-f0-9]{64,256}$/i.test(expectedHex)) return false;
  try {
    const salt = Buffer.from(saltHex, 'hex');
    const expected = Buffer.from(expectedHex, 'hex');
    const actual = crypto.scryptSync(String(password), salt, expected.length);
    return actual.length === expected.length && crypto.timingSafeEqual(actual, expected);
  } catch {
    return false;
  }
}

function rejectCrossSite(req, res) {
  if (req.get('sec-fetch-site') === 'cross-site') {
    res.status(403).json({ status: 'error', error: { code: 'CROSS_SITE_REQUEST', message: 'Cross-site authentication requests are not allowed.' } });
    return true;
  }
  const origin = req.get('origin');
  const expectedOrigin = `${req.protocol}://${req.get('host')}`;
  if (origin && origin !== expectedOrigin) {
    res.status(403).json({ status: 'error', error: { code: 'INVALID_ORIGIN', message: 'Authentication request origin does not match this server.' } });
    return true;
  }
  return false;
}

function loginHandler(req, res) {
  if (!AUTH_CONFIGURED) {
    return res.status(503).json({ status: 'error', error: { code: 'AUTH_NOT_CONFIGURED', message: 'Dashboard login is not configured. Run scripts/setup-dashboard-auth.ps1 and add the generated values to .env.' } });
  }
  if (rejectCrossSite(req, res)) return;

  const ip = req.ip || req.socket.remoteAddress || 'unknown';
  const rate = checkLoginRate(ip);
  if (rate.blocked) {
    res.setHeader('Retry-After', String(rate.retryAfter));
    return res.status(429).json({ status: 'error', error: { code: 'LOGIN_TEMPORARILY_BLOCKED', message: 'Too many failed attempts. Try again later.' } });
  }

  const username = String(req.body?.username || '').trim();
  const password = String(req.body?.password || '');
  const validUser = safeEqual(username.toLowerCase(), USERNAME.toLowerCase());
  const validPassword = verifyPassword(password);
  if (!validUser || !validPassword) {
    recordFailedLogin(ip);
    return res.status(401).json({ status: 'error', error: { code: 'INVALID_CREDENTIALS', message: 'Username or password is incorrect.' } });
  }

  clearLoginAttempt(ip);
  const token = createSession(USERNAME);
  const cookieParts = [
    `${COOKIE_NAME}=${encodeURIComponent(token)}`,
    'Path=/',
    `Max-Age=${SESSION_MAX_AGE_SECONDS}`,
    'HttpOnly',
    'SameSite=Strict',
  ];
  if (COOKIE_SECURE) cookieParts.push('Secure');
  res.setHeader('Set-Cookie', cookieParts.join('; '));
  res.setHeader('Cache-Control', 'no-store');
  return res.json({
    status: 'ok',
    user: { username: USERNAME },
    expiresAt: Date.now() + SESSION_MAX_AGE_SECONDS * 1000,
    redirectTo: '/dashboard',
  });
}

function logoutHandler(req, res) {
  if (rejectCrossSite(req, res)) return;
  const cookieParts = [
    `${COOKIE_NAME}=`,
    'Path=/',
    'Max-Age=0',
    'HttpOnly',
    'SameSite=Strict',
  ];
  if (COOKIE_SECURE) cookieParts.push('Secure');
  res.setHeader('Set-Cookie', cookieParts.join('; '));
  res.setHeader('Cache-Control', 'no-store');
  return res.json({ status: 'ok', message: 'Logged out.' });
}

function sessionHandler(req, res) {
  res.setHeader('Cache-Control', 'no-store');
  if (!AUTH_CONFIGURED) {
    return res.status(503).json({ status: 'error', error: { code: 'AUTH_NOT_CONFIGURED', message: 'Dashboard authentication is not configured.' } });
  }
  if (!req.dashboardUser) {
    return res.status(401).json({ status: 'error', error: { code: 'AUTH_REQUIRED', message: 'Please sign in to CampusX.' } });
  }
  return res.json({ status: 'ok', user: req.dashboardUser });
}

function requireDashboardPage(req, res, next) {
  if (!AUTH_CONFIGURED) return res.redirect('/login.html?setup=required');
  if (!req.dashboardUser) {
    const nextPath = encodeURIComponent(`${req.path}${req.url.includes('?') ? req.url.slice(req.path.length) : ''}`);
    return res.redirect(`/login.html?next=${nextPath}`);
  }
  next();
}

function requireDashboardApi(req, res, next) {
  // Keep the basic process health endpoint public for diagnostics.
  if (req.path === '/health') return next();
  if (!AUTH_CONFIGURED) {
    return res.status(503).json({ status: 'error', error: { code: 'AUTH_NOT_CONFIGURED', message: 'Dashboard authentication is not configured.' } });
  }
  if (!req.dashboardUser) {
    return res.status(401).json({ status: 'error', error: { code: 'AUTH_REQUIRED', message: 'Please sign in to CampusX.' } });
  }
  next();
}

module.exports = {
  AUTH_CONFIGURED,
  sessionMiddleware,
  loginHandler,
  logoutHandler,
  sessionHandler,
  requireDashboardPage,
  requireDashboardApi,
};
